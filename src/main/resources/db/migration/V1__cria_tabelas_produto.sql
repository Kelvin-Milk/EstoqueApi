CREATE TABLE tipo_produto
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    descricao VARCHAR(100)                            NOT NULL,
    CONSTRAINT pk_tipo_produto PRIMARY KEY (id),
    CONSTRAINT uc_tipo_produto_descricao UNIQUE (descricao)
);
INSERT INTO tipo_produto (descricao) VALUES ('Eletrônico'), ('Eletrodoméstico'), ('Móvel');

CREATE TABLE produto
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo             VARCHAR(50)                             NOT NULL,
    descricao          VARCHAR(255)                            NOT NULL,
    tipo_produto_id    BIGINT                                  NOT NULL,
    valor_fornecedor   DECIMAL(15, 2)                          NOT NULL,
    quantidade_estoque INTEGER                                 NOT NULL DEFAULT 0,
    versao             BIGINT                                  NOT NULL DEFAULT 0,
    CONSTRAINT pk_produto PRIMARY KEY (id),
    CONSTRAINT uc_produto_codigo UNIQUE (codigo),
    CONSTRAINT fk_produto_on_tipo_produto FOREIGN KEY (tipo_produto_id) REFERENCES tipo_produto (id),
    CONSTRAINT ck_produto_valor_fornecedor CHECK (valor_fornecedor >= 0),
    CONSTRAINT ck_produto_quantidade_estoque CHECK (quantidade_estoque >= 0)
);

CREATE INDEX idx_produto_tipo_produto ON produto (tipo_produto_id);