CREATE TABLE movimento_estoque
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    produto_id        BIGINT         NOT NULL,
    tipo              VARCHAR(50)    NOT NULL,
    quantidade        INTEGER        NOT NULL,
    valor_venda       DECIMAL(15, 2),
    custo_unitario    DECIMAL(15, 2) NOT NULL,
    data_movimentacao TIMESTAMP      NOT NULL,
    CONSTRAINT pk_movimento_estoque PRIMARY KEY (id),
    CONSTRAINT fk_movimento_estoque_produto FOREIGN KEY (produto_id) REFERENCES produto (id),
    CONSTRAINT ck_movimento_estoque_tipo CHECK (tipo IN ('ENTRADA', 'SAIDA')),
    CONSTRAINT ck_movimento_estoque_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_movimento_estoque_valor_venda CHECK (
        (tipo = 'SAIDA' AND valor_venda IS NOT NULL AND valor_venda >= 0)
            OR (tipo = 'ENTRADA' AND valor_venda IS NULL)
        )
);

CREATE INDEX idx_movimento_estoque_produto_tipo ON movimento_estoque (produto_id, tipo);